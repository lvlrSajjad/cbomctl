FENCE = re.compile(r"^(?P<ind>[ \t]*)```(?P<lang>[A-Za-z0-9_+-]*)(?P<info>[^`]*)$")
COMMENT = re.compile(r"<!--(?P<body>.*?)-->", re.S)

_pypi_cache: dict[str, str] = {}


def shown(path: Path) -> Path:
    """Repo-relative when we can, absolute for a scratch doc under test."""
    try:
        return path.relative_to(ROOT)
    except ValueError:
        return path


class Block:
    def __init__(self, path: Path, line: int, lang: str, body: list[str], note: str):
        self.path, self.line, self.lang, self.body = path, line, lang, body
        self.note = " ".join(note.split())

    @property
    def where(self) -> str:
        return f"{shown(self.path)}:{self.line}"

    def annotation(self, kind: str) -> str | None:
        """The reason attached to `<!-- kind: reason -->`, or "" for a bare tag."""
        m = re.match(rf"{kind}\s*:\s*(.*)$", self.note, re.S)
        if m:
            return m.group(1).strip()
        return "" if self.note.strip() == kind else None


def blocks(path: Path):
    lines = path.read_text().split("\n")
    i = 0
    while i < len(lines):
        m = FENCE.match(lines[i])
        if not m:
            i += 1
            continue
        start, body = i + 1, []
        j = i + 1
        while j < len(lines) and not re.match(r"^[ \t]*```\s*$", lines[j]):
            body.append(lines[j])
            j += 1
        # The annotation is the HTML comment ending on the line above the fence.
        note = ""
        k = i - 1
        if k >= 0 and lines[k].rstrip().endswith("-->"):
            while k >= 0 and "<!--" not in lines[k]:
                k -= 1
            if k >= 0:
                cm = COMMENT.search("\n".join(lines[k:i]))
                if cm:
                    note = cm.group("body")
        yield Block(path, start, m.group("lang").lower(), body, note)
        i = j + 1


def scratch() -> Path:
    """A directory where the docs' placeholder filenames are real CBOMs."""
    d = Path(tempfile.mkdtemp(prefix="cbomctl-docs-"))
    for name, fixture in PLACEHOLDERS.items():
        shutil.copy(FIXTURES / fixture, d / name)
    shutil.copy(ROOT / "cbomctl.yaml.example", d / "cbomctl.yaml")
    shutil.copy(ROOT / "cbomctl.yaml.example", d / "cbomctl.yaml.example")
    (d / "tests").symlink_to(ROOT / "tests")
    return d


def run_cbomctl(args: list[str], cwd: Path) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "cbomctl.cli", *args],
        capture_output=True, text=True, cwd=cwd,
        env={**os.environ, "PYTHONPATH": str(SRC), "NO_COLOR": "1",
             "TERM": "dumb", "COLUMNS": "100"},
    )


def pypi_has(name: str) -> str:
    """PASS / FAIL / SKIP for `pip install <name>` resolving on the index."""
    if name in _pypi_cache:
        return _pypi_cache[name]
    url = f"https://pypi.org/pypi/{name}/json"
    try:
        with urllib.request.urlopen(url, timeout=10) as fh:
            json.load(fh)
        verdict = "PASS"
    except urllib.error.HTTPError as exc:
        verdict = "FAIL" if exc.code == 404 else "SKIP"
    except Exception:
        # A python.org build with no CA bundle cannot verify pypi.org, and that
        # is a fact about this laptop, not about the package. Ask curl before
        # reporting the claim unchecked.
        code = subprocess.run(
            ["curl", "-sS", "-o", os.devnull, "-w", "%{http_code}", "--max-time", "15", url],
            capture_output=True, text=True).stdout.strip()
        verdict = {"200": "PASS", "404": "FAIL"}.get(code, "SKIP")
    _pypi_cache[name] = verdict
    return verdict


def all_commands(body: list[str]) -> bool:
    """True for an untagged fence that is only commands, not a transcript.

    A block that opens `$ cbomctl verdict ...` and then shows the matrix is a
    transcript: its command half is not what needs checking, its output half
    is. Those go to `check_output` and must be generated.
    """
    lines = [l.strip() for l in body if l.strip()]
    return bool(lines) and all(
        l.lstrip("$ ").startswith("cbomctl ") or l.startswith("#") for l in lines)


def check_repo_local(line: str) -> tuple[str | None, str]:
    """Resolve commands that point at this repo, without running them.

    `./scripts/check.sh` invokes this file, so executing it here would recurse.
    What is checkable without running is whether the thing named exists — which
    is the failure mode that actually happens: a script renamed, an extra
    dropped from `pyproject.toml`, a path in a `cat` that moved.
    """
    m = re.match(r"^(?:\./)?(scripts/[\w.-]+)(?:\s.*)?$", line)
    if not m:
        m = re.match(r"^python3?\s+(scripts/[\w.-]+)(?:\s.*)?$", line)
    if m:
        target = ROOT / m.group(1)
        if not target.exists():
            return "FAIL", f"{m.group(1)} does not exist"
        if line.startswith("./") and not os.access(target, os.X_OK):
            return "FAIL", f"{m.group(1)} is not executable"
        return "CHECKED", f"{m.group(1)} exists"

    m = re.match(r"^pip3? install -e ['\"]?\.\[(\w+)\]['\"]?$", line)
    if m:
        extras = (ROOT / "pyproject.toml").read_text()
        block = extras.split("[project.optional-dependencies]", 1)
        if len(block) < 2 or not re.search(rf"^{m.group(1)}\s*=", block[1], re.M):
            return "FAIL", f"pyproject declares no `{m.group(1)}` extra"
        return "CHECKED", f"`{m.group(1)}` extra is declared in pyproject.toml"

    if re.match(r"^pytest(\s|$)", line):
        deps = (ROOT / "pyproject.toml").read_text()
        return ("CHECKED", "pytest is a declared test dependency") if "pytest" in deps \
            else ("FAIL", "pytest is not a declared dependency")

    m = re.match(r"^cat\s+([\w./-]+)$", line)
    if m:
        target = ROOT / m.group(1)
        return ("CHECKED", f"{m.group(1)} exists") if target.exists() \
            else ("FAIL", f"{m.group(1)} does not exist")

    return None, ""


def check_shell(b: Block, cwd: Path, report: list) -> bool:
    reason = b.annotation("unverified")
    if reason is not None:
        if not reason:
            report.append(("FAIL", b.where, "`unverified` with no reason given"))
            return False
        report.append(("SKIP", b.where, f"unverified — {reason}"))
        return True

    ok = True
    for raw in b.body:
        line = raw.strip().lstrip("$ ").strip()
        trailing = re.search(r"\s+#\s*(.*)$", line)
        line = re.sub(r"\s+#.*$", "", line)          # trailing prose comment
        if not line or line.startswith("#"):
            continue

        # One unrunnable line should not cost a block its other checks, so the
        # annotation is available per line as well: `cmd  # unverified: why`.
        if trailing and trailing.group(1).startswith("unverified:"):
            why = trailing.group(1)[len("unverified:"):].strip()
            if not why:
                report.append(("FAIL", b.where,
                               f"`{line}` — `unverified` with no reason given"))
                ok = False
            else:
                report.append(("SKIP", b.where, f"`{line}` — unverified: {why}"))
            continue

        if re.match(r"^(pip|pip3|python3? -m pip) install ([A-Za-z0-9._-]+)$", line):
            name = line.split()[-1]
            verdict = pypi_has(name)
            report.append((verdict, b.where,
                           f"`{line}` — {name} on PyPI"
                           if verdict != "SKIP" else
                           f"`{line}` — index unreachable, not verified"))
            ok &= verdict != "FAIL"
            continue

        if not line.startswith("cbomctl "):
            verdict, detail = check_repo_local(line)
            if verdict is None:
                report.append(("FAIL", b.where, (
                    f"`{line}` is not a cbomctl invocation and the block carries "
                    f"no `<!-- unverified: reason -->`")))
                ok = False
            else:
                report.append((verdict, b.where, f"`{line}` — {detail}"))
                ok &= verdict != "FAIL"
            continue

        if re.search(r"[|;&><`]|\$\(", line):
            report.append(("FAIL", b.where,
                           f"`{line}` uses shell plumbing; run it or annotate it"))
            ok = False
            continue

        proc = run_cbomctl(shlex.split(line)[1:], cwd)
        blew_up = proc.returncode == 2 or "No such command" in proc.stderr
        report.append(("FAIL" if blew_up else "RAN", b.where,
                       f"`{line}` → exit {proc.returncode}"
                       + (f"\n        {proc.stderr.strip().splitlines()[0]}"
                          if blew_up and proc.stderr.strip() else "")))
        ok &= not blew_up
    return ok


def check_synopsis(b: Block, cwd: Path, report: list) -> bool:
    """A usage sketch is not runnable, but its flags must be real."""
    ok = True
    for raw in b.body:
        line = raw.strip()
        if not line:
            continue
        sub = None
        if line.startswith("cbomctl "):
            rest = line[len("cbomctl "):].split()
            sub = rest[0] if rest and not rest[0].startswith("-") else None
        if sub:
            proc = run_cbomctl([sub, "--help"], cwd)
            if proc.returncode != 0:
                report.append(("FAIL", b.where, f"no such subcommand: `{sub}`"))
                ok = False
                continue
            b._help = proc.stdout                                # noqa: SLF001
        help_text = getattr(b, "_help", "")
        for flag in re.findall(r"(?<![\w-])--[a-z][a-z0-9-]*", line):
            if help_text and flag not in help_text:
                report.append(("FAIL", b.where,
                               f"`{flag}` is not a flag the CLI has"))
                ok = False
    if ok:
        report.append(("CHECKED", b.where, "synopsis — subcommands and flags exist"))
    return ok


def check_prose_flags(path: Path, cwd: Path, report: list, help_text: str) -> bool:
    """Every `--flag` written in prose must be one the CLI has, or be foreign.

    Fenced commands are only half the claims a page makes. The other half is
    sentences and reference tables, and that is where `--strict-unknown`
    survived four releases.
    """
    ok = True
    for m in re.finditer(r"`(--[a-z][a-z0-9-]*)", path.read_text()):
        flag = m.group(1)
        if flag in FOREIGN_FLAGS or cli_has(flag, help_text):
            continue
        line = path.read_text()[:m.start()].count("\n") + 1
        report.append(("FAIL", f"{shown(path)}:{line}", (
            f"`{flag}` is not a flag cbomctl has. If it belongs to another "
            f"tool or is future work, add it to FOREIGN_FLAGS with its owner")))
        ok = False
    return ok


def cli_has(flag: str, help_text: str) -> bool:
    """Does `--help` offer exactly this flag, and not merely start with it?

    A plain substring test passes `--jurisdiction` because `--jurisdictions`
    is in the help — so the singular, which is the likelier typo of the two,
    was the one thing this check could not see. Found by injecting it into
    `action.yml` and into a scratch page under `docs/`: both passed.
    """
    return re.search(rf"{re.escape(flag)}(?![A-Za-z0-9-])", help_text) is not None


def cli_help(cwd: Path) -> str:
    """Every subcommand's --help, concatenated, at a width that never wraps."""
    text = run_cbomctl(["--help"], cwd).stdout
    for sub in ("verdict", "prioritize", "plan", "normalize", "policies"):
        proc = subprocess.run(
            [sys.executable, "-m", "cbomctl.cli", sub, "--help"],
            capture_output=True, text=True, cwd=cwd,
            env={**os.environ, "PYTHONPATH": str(SRC), "NO_COLOR": "1",
                 "TERM": "dumb", "COLUMNS": "200"})
        text += proc.stdout
    return text


def check_output(b: Block, cwd: Path, report: list) -> bool:
    """An untagged fence in prose has to say what it is.

    Heuristics were tried first — look for `└ `, for `CONFLICTS (`, for a
    matrix header — and every one of them missed something. The fiction on the
    docs-site landing page had a bare `CONFLICTS` with no count; the block in
    `purpose.md` was a paraphrase with no tell at all. A fence either declares
    itself or it fails; there are few enough of them for that to be cheap.
    """
    if b.annotation("cbomctl") is not None:
        return True                       # gen_article_blocks.py owns this one

    cmd = b.annotation("excerpt")
    if cmd is not None:
        # Prose that quotes a few lines of output, rewrapped to the narrower
        # column the prose uses. `illustrative` would excuse it; this pins it
        # to the command instead, and checks against that command's *whole*
        # output — the quote is often a line the pasted block truncates away.
        if not cmd:
            report.append(("FAIL", b.where,
                           "`excerpt` needs the command it quotes: "
                           "`<!-- excerpt: verdict ... -->`"))
            return False
        args = shlex.split(cmd)
        proc = run_cbomctl(args[1:] if args[:1] == ["cbomctl"] else args, cwd)
        quoted = " ".join(" ".join(b.body).split())
        if quoted and quoted in " ".join(proc.stdout.split()):
            report.append(("CHECKED", b.where,
                           f"excerpt — found verbatim in `cbomctl {cmd}` output"))
            return True
        report.append(("FAIL", b.where, (
            f"marked `excerpt` of `cbomctl {cmd}`, but that command's output "
            f"does not contain it")))
        return False

    for kind in ("illustrative", "unverified"):
        reason = b.annotation(kind)
        if reason:
            report.append(("SKIP", b.where, f"{kind} — {reason}"))
            return True
        if reason == "":
            report.append(("FAIL", b.where, f"`{kind}` with no reason given"))
            return False
    report.append(("FAIL", b.where, (
        "untagged fence — if it is tool output give it a `<!-- cbomctl: ... -->` "
        "marker so it is generated; if it is a usage sketch mark it "
        "`<!-- synopsis -->`; otherwise `<!-- illustrative: reason -->`")))
    return False


#: Actions in the docs whose `action.yml` is fetched from their own repository
#: at the ref the snippet names, so `with:` keys are checked against what the
#: action really declares. `docs/ci.md` used to pass `with: { output: cbom.json }`
#: to CBOMkit's action, which declares no inputs at all; that half of the page
#: was corrected by hand and then went back to being unchecked. Fetching is the
#: only way to check somebody else's action, and it is why an entry here is
#: SKIPped rather than failed when the network is unreachable.
#:
#: An action *not* listed here is reported unchecked with its name, so adding
#: one to a snippet is a visible decision rather than a silent hole.
THIRD_PARTY_ACTIONS = {
    "actions/checkout",
    "actions/upload-artifact",
    "cbomkit/cbomkit-action",
    "github/codeql-action/upload-sarif",
}

#: Docker actions take no `with:` inputs; they are configured by environment
#: variables, which `action.yml` does not declare. What can still be checked is
#: that the name we tell a reader to set is one the action documents. Value:
#: the path in the action's repo that documents them.
ACTION_ENV_DOCS = {
    "cbomkit/cbomkit-action": "README.md",
}

_action_cache: dict[str, str | None] = {}


def fetch_raw(repo: str, ref: str, path: str) -> str | None:
    """A file from a GitHub repo at a ref, or None if it cannot be reached."""
    key = f"{repo}@{ref}/{path}"
    if key in _action_cache:
        return _action_cache[key]
    url = f"https://raw.githubusercontent.com/{repo}/{ref}/{path}"
    text: str | None = None
    try:
        with urllib.request.urlopen(url, timeout=15) as fh:
            text = fh.read().decode()
    except urllib.error.HTTPError as exc:
        text = "" if exc.code == 404 else None
    except Exception:
        # Same laptop-versus-package distinction `pypi_has` makes: a python.org
        # build with no CA bundle cannot verify github.com, and that is a fact
        # about this machine.
        proc = subprocess.run(
            ["curl", "-sS", "--max-time", "20", "-w", "\n%{http_code}", url],
            capture_output=True, text=True)
        body, _, code = proc.stdout.rpartition("\n")
        text = body if code.strip() == "200" else ("" if code.strip() == "404"
                                                   else None)
    _action_cache[key] = text
    return text


def declared_inputs(action_yml: str) -> set[str]:
    """Input names in an `action.yml`. Empty for an action declaring none."""
    try:
        import yaml
        doc = yaml.safe_load(action_yml) or {}
        return set((doc.get("inputs") or {}).keys())
    except Exception:
        return set()


def check_workflow(b: Block, report: list) -> bool:
    """Every action a CI snippet names must take the inputs the snippet passes.

    Both halves, not just ours. The half this file could not reach was named on
    the page as transcribed-not-run, and that annotation was doing the work a
    check should have been doing: their `action.yml` is a file, it is fetchable,
    and reading it is the whole of what "read against their action.yml" meant.
    """
    ok = True
    seen = False
    for line in b.body:
        m = re.search(r"uses:\s*([A-Za-z0-9._/-]+)@(\S+)", line)
        if not m:
            continue
        seen = True
        repo_path, ref = m.group(1), m.group(2)
        if repo_path == "lvlrSajjad/cbomctl":
            ok &= check_our_action(b, ref, report)
        else:
            ok &= check_third_party_action(b, repo_path, ref, report)
    if not seen:
        return True
    return ok


def check_our_action(b: Block, ref: str, report: list) -> bool:
    declared = declared_inputs((ROOT / "action.yml").read_text())
    ok = True
    known = subprocess.run(["git", "tag"], capture_output=True, text=True,
                           cwd=ROOT).stdout.split()
    if not known:
        # A shallow checkout has no tags. Saying nothing here would let the
        # check pass by accident, which is the failure this file exists to stop.
        report.append(("SKIP", b.where,
                       f"`@{ref}` unresolved — no tags in this checkout "
                       f"(fetch-depth: 0 is needed to verify it)"))
    elif ref not in known:
        report.append(("FAIL", b.where, f"`@{ref}` is not a tag in this repo"))
        ok = False

    used = mapping_keys(b.body, f"lvlrSajjad/cbomctl@{ref}", "with")
    for key in used:
        if key not in declared:
            report.append(("FAIL", b.where, f"`with: {key}` is not an action input"))
            ok = False
    if ok:
        report.append(("CHECKED", b.where,
                       f"action `@{ref}` exists; inputs {sorted(used)} declared"))
    return ok


def check_third_party_action(b: Block, repo_path: str, ref: str,
                             report: list) -> bool:
    used = mapping_keys(b.body, f"{repo_path}@{ref}", "with")
    env = mapping_keys(b.body, f"{repo_path}@{ref}", "env")

    if repo_path not in THIRD_PARTY_ACTIONS:
        report.append(("SKIP", b.where, (
            f"`{repo_path}@{ref}` is not resolved — add it to "
            f"THIRD_PARTY_ACTIONS to check the inputs this page passes it")))
        return True

    repo = "/".join(repo_path.split("/")[:2])
    subdir = "/".join(repo_path.split("/")[2:])
    prefix = f"{subdir}/" if subdir else ""
    action_yml = fetch_raw(repo, ref, f"{prefix}action.yml")
    if action_yml == "":
        action_yml = fetch_raw(repo, ref, f"{prefix}action.yaml")
    if action_yml is None:
        report.append(("SKIP", b.where, (
            f"`{repo_path}@{ref}` — github.com unreachable, inputs "
            f"{sorted(used)} not verified")))
        return True
    if action_yml == "":
        report.append(("FAIL", b.where, (
            f"`{repo_path}@{ref}` has no action.yml — the ref is wrong, or the "
            f"action moved")))
        return False

    ok = True
    declared = declared_inputs(action_yml)
    for key in used:
        if key not in declared:
            report.append(("FAIL", b.where, (
                f"`with: {key}` is not an input of `{repo_path}@{ref}`"
                + (f"; it declares none at all" if not declared else
                   f"; it declares {sorted(declared)}"))))
            ok = False

    if env:
        doc_path = ACTION_ENV_DOCS.get(repo_path)
        docs = fetch_raw(repo, ref, doc_path) if doc_path else None
        if not doc_path:
            report.append(("SKIP", b.where, (
                f"`env:` {sorted(env)} on `{repo_path}@{ref}` — nothing in the "
                f"action declares environment variables; add the file that "
                f"documents them to ACTION_ENV_DOCS to check the names")))
        elif docs is None:
            report.append(("SKIP", b.where, (
                f"`env:` {sorted(env)} — {repo}/{doc_path} unreachable")))
        else:
            for key in env:
                # Whole-word: `CBOMKIT_LANGUAGE` is a substring of the real
                # `CBOMKIT_LANGUAGES`, and a substring match would pass it.
                if not re.search(rf"\b{re.escape(key)}\b", docs):
                    report.append(("FAIL", b.where, (
                        f"`env: {key}` is not documented in "
                        f"{repo}/{doc_path} at `{ref}`")))
                    ok = False
    if ok:
        report.append(("CHECKED", b.where, (
            f"`{repo_path}@{ref}` — with {sorted(used)} declared, env "
            f"{sorted(env)} documented" if (used or env) else
            f"`{repo_path}@{ref}` resolves and is passed nothing")))
    return ok


def mapping_keys(body: list[str], uses: str, block: str) -> list[str]:
    """Keys of the `with:` (or `env:`) mapping on the step that `uses` this."""
    keys: list[str] = []
    for i, line in enumerate(body):
        if uses not in line:
            continue
        step_indent = len(line) - len(line.lstrip())
        inside = False
        for rest in body[i + 1:]:
            if not rest.strip():
                continue
            indent = len(rest) - len(rest.lstrip())
            if indent <= step_indent and rest.lstrip().startswith("- "):
                break                                   # next step
            m = re.match(rf"^\s*{block}:\s*\{{(.*)\}}\s*$", rest)
            if m:                                       # inline `with: { a: b }`
                keys += re.findall(r"([\w-]+)\s*:", m.group(1))
                continue
            if re.match(rf"^\s*{block}:\s*$", rest):
                inside = True
                continue
            if re.match(r"^\s*[\w-]+:\s*$", rest) and indent <= step_indent + 2:
                inside = False                          # a sibling of `with:`
            if inside and indent > step_indent + 2:
                m = re.match(r"^\s*([\w-]+):", rest)
                if m:
                    keys.append(m.group(1))
        break
    return sorted(set(keys))


def check_block(b: Block, cwd: Path, report: list) -> bool:
    """Route one fence to the check its annotation and language call for.

    One function, so `tests/test_check_commands.py` exercises the same routing
    the script does. Duplicating this in the tests would let the thing that
    proves the checker works drift from the checker.
    """
    if b.annotation("illustrative") is not None:
        # Deliberately not a real thing, whatever it looks like — a layout
        # drawing, or a blank for a bug reporter to fill in.
        return check_output(b, cwd, report)
    if b.annotation("synopsis") is not None:
        return check_synopsis(b, cwd, report)
    if b.lang in SHELL_LANGS or (not b.lang and all_commands(b.body)):
        return check_shell(b, cwd, report)
    if b.lang in ("", "text"):
        return check_output(b, cwd, report)
    if b.lang in ("yaml", "yml"):
        return check_workflow(b, report)
    reason = b.annotation("unverified")
    if reason is not None:
        if not reason:
            report.append(("FAIL", b.where, "`unverified` with no reason given"))
            return False
        report.append(("SKIP", b.where, f"unverified — {reason}"))
    return True


#: `action.yml` ships a command too, and until now nothing read it. The
#: action's composite step builds a `cbomctl` argv and runs it; what was
#: checked was the *declared inputs* (`check_our_action`, against the snippet
#: in `docs/ci.md`) and never the argv itself. CI's `dogfood` job does run the
#: action, but down one path only — `format: sarif` with `output:` set, and
#: both booleans left false. The `--strict` and `--fail-on-warn` branches are
#: executed by nothing, anywhere.
#:
#: That was verified by injecting `--jurisdiction` and `--fail-on-warn-typo`
#: into `action.yml`: `check_commands.py --check` exited 0 and all 450 tests
#: passed. The first would have broken every user of the action, the second
#: only the user who set `strict:` or `fail-on-warn:` — silently, because no
#: run here or in CI ever composes that argv.
#:
#: This is the README gap in a different file. `aa7e3d0` fixed a checker whose
#: file list omitted a real prose surface; this one's file list omitted a real
#: *command* surface. An argv a reader never sees but every action user
#: executes is exactly as much of a claim as a fenced command.
#:
#: Flags on a line that is neither building nor invoking `cbomctl` belong to
#: something else — `pip install --quiet` — and are left alone.
ACTION_ARGV = re.compile(r"args\+?=\(|(?:^|\s)cbomctl\s")


def action_argv(doc: dict) -> tuple[set[str], set[str], set[str]]:
    """Subcommands, flags and `inputs.` names the action's shell body uses."""
    subs: set[str] = set()
    flags: set[str] = set()
    used: set[str] = set()
    for step in (doc.get("runs") or {}).get("steps") or []:
        body = step.get("run") or ""
        for line in body.split("\n"):
            # An undeclared `inputs.x` is not an error in Actions — it expands
            # to the empty string. So it is read from every line, not just the
            # cbomctl ones, and checked against what the action declares.
            used.update(re.findall(r"inputs\.([A-Za-z0-9_-]+)", line))
            if not ACTION_ARGV.search(line):
                continue
            subs.update(re.findall(r"args\+?=\(\s*([a-z][a-z0-9-]*)", line))
            flags.update(re.findall(r"(--[a-z][a-z0-9-]+)", line))
    return subs, flags, used


def check_action_argv(cwd: Path, report: list, help_text: str,
                      path: Path | None = None) -> bool:
    """The argv `action.yml` hands cbomctl must name real things, and run.

    Names are checked against `--help`, and then the argv the action composes
    with *every* option set is executed — the combination `dogfood` never
    reaches. A wrong flag there is a usage error (exit 2), which is the one
    exit code the action's own contract says means the invocation, not the
    CBOM, was wrong.
    """
    path = path or ROOT / "action.yml"
    text = path.read_text()
    where = str(shown(path))
    try:
        import yaml
        doc = yaml.safe_load(text) or {}
    except Exception as exc:
        report.append(("FAIL", where, f"does not parse as YAML: {exc}"))
        return False

    declared = declared_inputs(text)
    subs, flags, used = action_argv(doc)
    top = run_cbomctl(["--help"], cwd).stdout
    ok = True

    for sub in sorted(subs):
        if sub not in top:
            report.append(("FAIL", where,
                           f"`{sub}` is not a cbomctl subcommand"))
            ok = False
    for flag in sorted(flags):
        if not cli_has(flag, help_text):
            report.append(("FAIL", where, (
                f"`{flag}` is not a flag cbomctl has — action.yml hands it to "
                f"every user of this action")))
            ok = False
    for name in sorted(used - declared):
        report.append(("FAIL", where, (
            f"`inputs.{name}` is not a declared input; Actions expands it to "
            f"the empty string rather than failing")))
        ok = False
    if not ok:
        return False

    # Compose the argv the way the step does, with every option turned on, and
    # run it. Defaults come from `action.yml` itself so the check follows the
    # action rather than a copy of it.
    inputs = doc.get("inputs") or {}
    default = lambda k, fb: str((inputs.get(k) or {}).get("default") or fb)
    argv = ["verdict", "app-cbom.json",
            "--jurisdictions", default("jurisdictions", "bsi-de"),
            "--format", default("format", "sarif"),
            "--config", "cbomctl.yaml", "--strict", "--fail-on-warn"]
    proc = run_cbomctl(argv, cwd)
    if proc.returncode == 2:
        report.append(("FAIL", where, (
            f"the argv this action composes is a usage error (exit 2): "
            f"`cbomctl {' '.join(argv)}` — {proc.stderr.strip().splitlines()[-1:]}")))
        return False
    report.append(("RAN", where, (
        f"`cbomctl {' '.join(argv)}` → exit {proc.returncode} — the every-option "
        f"argv, which `dogfood` never composes")))
    report.append(("CHECKED", where, (
        f"subcommand {sorted(subs)}, flags {sorted(flags)} and inputs "
        f"{sorted(used)} all exist")))
    return True


def main() -> int:
    check = "--check" in sys.argv
    cwd = scratch()
    report: list[tuple[str, str, str]] = []
    ok = True
    try:
        paths: list[Path] = []
        for base in SEARCH:
            paths += [base] if base.is_file() else sorted(base.rglob("*.md"))
        help_text = cli_help(cwd)
        for path in paths:
            if any(g in path.parents for g in GENERATED):
                continue
            ok &= check_prose_flags(path, cwd, report, help_text)
            for b in blocks(path):
                ok &= check_block(b, cwd, report)
        ok &= check_action_argv(cwd, report, help_text)
    finally:
        shutil.rmtree(cwd, ignore_errors=True)

    width = max((len(w) for _, w, _ in report), default=0)
    for verdict, where, detail in report:
        print(f"  {verdict:<8} {where:<{width}}  {detail}")

    tally = {v: sum(1 for x, _, _ in report if x == v) for v in
             ("RAN", "PASS", "CHECKED", "SKIP", "FAIL")}
    print(f"\n  {tally['RAN']} commands executed, {tally['PASS']} resolved on PyPI, "
          f"{tally['CHECKED']} statically checked, {tally['SKIP']} marked unverified, "
          f"{tally['FAIL']} failing")
    if not ok:
        print("\nA command presented as working must have been run. If it cannot "
              "be run here,\nsay so above the fence: <!-- unverified: reason -->")
        return 1
    return 0


